#!/usr/bin/env python3
"""EuroWatcher for Linux and macOS.

Shows every EuroMillions draw since 2004 and checks your numbers against them. This one file
serves the EuroWatcher page on this computer only (127.0.0.1), opens it in its own browser window,
and fetches new draws when the page asks. It needs nothing but Python 3.7 or newer.

    eurowatcher              open EuroWatcher
    eurowatcher --update     fetch the newest draws in the terminal
    eurowatcher --no-window  only start the server and print its address
    eurowatcher --selftest   check this installation without using the internet
"""

