def main(argv):
    if "--selftest" in argv:
        return selftest()
    if "--update" in argv:
        prepare_data()
        print("Fetching the newest draws (this can take up to a minute)…")
        r = update()
        if not r["ok"]:
            print("The update did not work: " + r["message"])
            return 1
        print("%d draws on file, %d new, latest %s." % (r["total"], r["added"], r["latest"]))
        return 0
    if "--version" in argv:
        print("EuroWatcher " + VERSION)
        return 0
    if "-h" in argv or "--help" in argv:
        print(__doc__)
        return 0
    return run(show_window="--no-window" not in argv)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
