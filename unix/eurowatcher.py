MONTHS = {m: i + 1 for i, m in enumerate("Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split())}
TUESDAYS_SINCE = "2011-05-10"
STAR_12_SINCE = "2016-09-27"


def log(message):
    try:
        os.makedirs(DATA_DIR, exist_ok=True)
        path = os.path.join(DATA_DIR, "log.txt")
        if os.path.exists(path) and os.path.getsize(path) > 256 * 1024:
            os.remove(path)
        with open(path, "a", encoding="utf-8") as f:
            f.write(datetime.now().strftime("%Y-%m-%d %H:%M:%S") + "  " + message + "\n")
    except OSError:
        pass


# ---------------------------------------------------------------- the draw file

def parse_file(text):
    m = re.search(r"window\.EURO_DATA\s*=\s*(\{[\s\S]*\});?\s*$", text or "")
    if not m:
        raise ValueError("not a draw data file")
    root = json.loads(m.group(1))
    draws = [{"no": r[0], "date": r[1], "n": r[2], "s": r[3], "prizes": r[4], "winners": r[5],
              "gbp": r[6] if len(r) > 6 else None} for r in root["draws"]]
    return {"draws": draws, "checks": root.get("checks") or {}}


def num(v):
    if v is None:
        return "null"
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return repr(v) if isinstance(v, float) else str(v)


def row(d):
    arr = lambda xs: "null" if xs is None else "[" + ",".join(num(x) for x in xs) + "]"
    return "[%d,%s,%s,%s,%s,%s,%s]" % (d["no"], json.dumps(d["date"]), arr(d["n"]), arr(d["s"]),
                                       arr(d["prizes"]), arr(d["winners"]), num(d["gbp"]))


def serialize(draws, checks):
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.") + "%03dZ" % (datetime.now().microsecond // 1000)
    compact = lambda v: json.dumps(v, separators=(",", ":"), ensure_ascii=False)
    return "\n".join([
        "// Generated by tools/update-data.mjs or the EuroWatcher app. Do not edit by hand.",
        "window.EURO_DATA = {",
        ' "generated": %s,' % json.dumps(generated),
        ' "tiers": %s,' % compact(TIERS),
        ' "sources": %s,' % compact(SOURCES),
        ' "checks": %s,' % compact(checks),
        ' "draws": [',
        ",\n".join(row(d) for d in draws),
        " ]",
        "};",
        "",
    ])


def validate(d):
    issues = []
    star_max = 9 if d["date"] < TUESDAYS_SINCE else 11 if d["date"] < STAR_12_SINCE else 12
    ok = lambda xs, count, top: len(xs) == count and len(set(xs)) == count and all(1 <= x <= top for x in xs)
    if not ok(d["n"], 5, 50):
        issues.append("numbers out of range")
    if not ok(d["s"], 2, star_max):
        issues.append("stars out of range for that date (max %d)" % star_max)
    weekday = date.fromisoformat(d["date"]).weekday()   # Monday is 0
    if not (weekday == 4 or (weekday == 1 and d["date"] >= TUESDAYS_SINCE)):
        issues.append("not a draw day")
    return issues


def file_problems(draws):
    problems = []
    for i, d in enumerate(draws):
        if d["no"] != i + 1:
            problems.append("%s: draw number %s breaks the sequence" % (d["date"], d["no"]))
        if i and draws[i - 1]["date"] >= d["date"]:
            problems.append("%s: out of order" % d["date"])
        problems += ["%s: %s" % (d["date"], x) for x in validate(d)]
    return problems


# ---------------------------------------------------------------- the sources

def parse_list(text):
    draws = {}
    pattern = re.compile(r"^\s*(\d+),\s*\w{3},\s*(\d+),(\w{3}),(\d{4}),\s*(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),\s*(\d*),\s*(\d*)")
    for line in text.splitlines():
        m = pattern.match(line)
        if not m or m.group(3) not in MONTHS:
            continue
        g = m.groups()
        day = "%s-%02d-%02d" % (g[3], MONTHS[g[2]], int(g[1]))
        draws[day] = {"no": int(g[0]), "date": day, "n": sorted(int(x) for x in g[4:9]), "s": sorted(int(x) for x in g[9:11]),
                      "gbp": int(g[11]) if g[11] else None, "wins": int(g[12]) if g[12] else None}
    return draws


def parse_prizes(text):
    draws = {}
    for item in json.loads(text):
        day = str(item["date"])[:10]
        prizes = winners = None
        if item.get("prizes"):
            def find(t):
                for p in item["prizes"]:
                    if p.get("matched_numbers") == t[0] and p.get("matched_stars") == t[1]:
                        return p
                return None
            winners, prizes = [], []
            for i, t in enumerate(TIERS):
                p = find(t)
                winners.append(p.get("winners") if p else None)
                amount = p.get("prize") if p else None
                # A tier nobody won has no per-winner amount, except the jackpot, where the figure is the pot.
                prizes.append(None if amount is None or (i > 0 and amount == 0) else round(amount * 100) / 100)
        draws[day] = {"date": day, "n": sorted(int(x) for x in item["numbers"]), "s": sorted(int(x) for x in item["stars"]),
                      "prizes": prizes, "winners": winners}
    return draws


def parse_latest(text):
    day = re.search(r"<draw-date>(\d{4}-\d{2}-\d{2})<", text)
    n = sorted(int(x) for x in re.findall(r'<ball number="\d+">(\d+)<', text))
    s = sorted(int(x) for x in re.findall(r'<bonus-ball type="luckystar" number="\d+">(\d+)<', text))
    if not day or len(n) != 5 or len(s) != 2:
        raise ValueError("unrecognised format")
    winners = None
    block = re.search(r'<prize-tiers country="All">([\s\S]*?)</prize-tiers>', text)
    if block and re.search(r"<confirmed>Y<", text):
        by_level = {int(a): int(b) for a, b in re.findall(r'<prize-tier level="(\d+)"><number-of-winners>(\d+)<', block.group(1))}
        if len(by_level) == len(TIERS):
            winners = [by_level[i + 1] for i in range(len(TIERS))]
    no = re.search(r"<draw-number>(\d+)<", text)
    gbp = re.search(r"<jackpot-amount>([\d,]+)<", text)
    return {"no": int(no.group(1)) if no else None, "date": day.group(1), "n": n, "s": s, "winners": winners,
            "gbp": int(gbp.group(1).replace(",", "")) if gbp else None}


def build(previous, list_text, prizes_text, latest_text):
    lst = parse_list(list_text)
    if len(lst) < 1900:
        raise ValueError("the draw list came back incomplete")
    prizes, latest = {}, None
    if prizes_text:
        try:
            prizes = parse_prizes(prizes_text)
        except Exception as err:                # noqa: BLE001 - one bad source must not stop the update
            log("prizes source unreadable: %s" % err)
    if latest_text:
        try:
            latest = parse_latest(latest_text)
        except Exception as err:                # noqa: BLE001
            log("latest-draw feed unreadable: %s" % err)
    old = {d["date"]: d for d in (previous or [])}
    dates = sorted(set(lst) | set(prizes) | ({latest["date"]} if latest else set()))
    key = lambda c: "%s|%s" % (c["n"], c["s"])
    problems, out, cross, official = [], [], 0, False
    for i, day in enumerate(dates):
        L, P, O, before = lst.get(day), prizes.get(day), latest if latest and latest["date"] == day else None, old.get(day)
        copies = [c for c in (L, P, O) if c]
        if len({key(c) for c in copies}) > 1:
            problems.append("%s: sources disagree on the balls" % day)
        elif len(copies) > 1:
            cross += 1
            if O and i == len(dates) - 1:
                official = True
        d = {"no": L["no"] if L else (O["no"] if O and O["no"] else i + 1), "date": day, "n": copies[0]["n"], "s": copies[0]["s"]}
        if d["no"] != i + 1:
            problems.append("%s: draw number %s breaks the sequence (expected %d)" % (day, d["no"], i + 1))
        problems += ["%s: %s" % (day, x) for x in validate(d)]
        d["prizes"] = (P and P["prizes"]) or (before and before["prizes"]) or None
        d["winners"] = (P and P["winners"]) or (O and O["winners"]) or (before and before["winners"]) or None
        if not d["winners"] and L:
            # Only the list knows this draw. Its "0 winners" is trusted once the next draw shows the pot kept growing.
            nxt = lst.get(dates[i + 1]) if i + 1 < len(dates) else None
            jw = L["wins"]
            if jw == 0 and not (nxt and nxt["gbp"] is not None and L["gbp"] is not None and nxt["gbp"] >= L["gbp"] * 0.5):
                jw = None
            if jw is not None:
                d["winners"] = [jw] + [None] * (len(TIERS) - 1)
        d["gbp"] = (L and L["gbp"]) or (O and O["gbp"]) or (before and before["gbp"]) or None
        out.append(d)
    if previous and len(out) < len(previous):
        problems.append("only %d draws found but %d are already on file" % (len(out), len(previous)))
    if problems:
        raise ValueError("%d problem(s), first: %s" % (len(problems), problems[0]))
    return out, {"crossChecked": cross, "officialLatest": official, "withPrizes": sum(1 for d in out if d["prizes"])}


def fetch(url, retry=True):
    last = None
    for wait in ((0, 4, 10) if retry else (0,)):
        time.sleep(wait)
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (compatible; EuroWatcher/%s)" % VERSION, "Accept": "*/*"})
            with urllib.request.urlopen(req, timeout=45) as res:
                return res.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as err:
            last = err
            if err.code != 429 and err.code < 500:
                break
        except (urllib.error.URLError, OSError) as err:
            last = err
    raise last


def try_fetch(url):
    try:
        return fetch(url)
    except Exception as err:                    # noqa: BLE001
        log("could not read %s: %s" % (url, err))
        return None


_update_lock = threading.Lock()


def update():
    """Fetches the newest draws and saves them. Returns a dict the page understands."""
    with _update_lock:
        try:
            previous = parse_file(read_data().decode("utf-8"))["draws"]
        except Exception:                       # noqa: BLE001
            previous = []
        built, error, via = None, None, ""
        try:
            draws, checks = build(previous, fetch(SOURCES[0]["url"]), try_fetch(SOURCES[1]["url"]), try_fetch(SOURCES[2]["url"]))
            built, via = serialize(draws, checks), "sources"
            total = len(draws)
        except Exception as err:                # noqa: BLE001
            error = str(err)
            log("update from the sources failed: %s" % err)
        if built is None:
            try:
                copy = parse_file(fetch(GITHUB_COPY))
                problems = file_problems(copy["draws"])
                if problems:
                    raise ValueError(problems[0])
                if len(copy["draws"]) < len(previous):
                    raise ValueError("the online copy is older than the data on this computer")
                built, via, total = serialize(copy["draws"], copy["checks"]), "github", len(copy["draws"])
            except Exception as err:            # noqa: BLE001
                log("update from the online copy failed: %s" % err)
                return {"ok": False, "added": 0, "total": len(previous), "latest": "", "via": "", "message": error or str(err)}
        write_data(built)
        added = max(0, total - len(previous))
        latest = parse_file(built)["draws"][-1]["date"]
        log("updated via %s: %d draws, %d new, latest %s" % (via, total, added, latest))
        return {"ok": True, "added": added, "total": total, "latest": latest, "via": via, "message": ""}


# ---------------------------------------------------------------- the data on this computer

_data_lock = threading.Lock()


def count_draws(text):
    return len(re.findall(r'^\[\d+,"', text or "", re.M))


def prepare_data():
    """Puts the copy that comes with the program in place, unless the one on file is newer."""
    shipped_path = os.path.join(WEB, "data", "draws.js")
    if not os.path.isfile(shipped_path):
        shipped_path = os.path.join(WEB, "draws.js")
    with _data_lock:
        os.makedirs(DATA_DIR, exist_ok=True)
        try:
            with open(shipped_path, encoding="utf-8") as f:
                shipped = f.read()
        except OSError:
            return
        on_file = None
        if os.path.exists(DATA_FILE):
            with open(DATA_FILE, encoding="utf-8") as f:
                on_file = f.read()
        if count_draws(on_file) < count_draws(shipped):
            _write(shipped)


def read_data():
    with _data_lock:
        with open(DATA_FILE, "rb") as f:
            return f.read()


def write_data(text):
    with _data_lock:
        _write(text)


def _write(text):
    tmp = DATA_FILE + ".new"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, DATA_FILE)


# ---------------------------------------------------------------- the local server

class Handler(BaseHTTPRequestHandler):
    server_version = "EuroWatcher/" + VERSION
    last_request = [time.time()]

    def log_message(self, *args):               # keep the terminal quiet
        pass

    def send(self, status, body, ctype="text/plain; charset=utf-8", head_only=False):
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.end_headers()
        if not head_only:
            self.wfile.write(body)

    def allowed(self):
        # Only this program's own page may talk to it: the address must be exactly ours
        # (this blocks other web sites that try to reach it through a look-alike name).
        port = self.server.server_address[1]
        return self.headers.get("Host") in ("127.0.0.1:%d" % port, "localhost:%d" % port)

    def do_HEAD(self):
        self.do_GET(head_only=True)

    def do_GET(self, head_only=False):
        Handler.last_request[0] = time.time()
        if not self.allowed():
            return self.send(403, b"Forbidden")
        path = urllib.parse.urlsplit(self.path).path
        if path == "/api/status":
            return self.send(200, json.dumps({"app": "EuroWatcher", "version": VERSION}).encode(), "application/json")
        if path == "/data/draws.js":
            return self.send(200, read_data(), "text/javascript; charset=utf-8", head_only)
        if path in FILES:
            name, ctype = FILES[path]
            with open(os.path.join(WEB, name), "rb") as f:
                return self.send(200, f.read(), ctype, head_only)
        return self.send(404, b"Not found")

    def do_POST(self):
        Handler.last_request[0] = time.time()
        length = int(self.headers.get("Content-Length") or 0)
        if length:
            self.rfile.read(min(length, 65536))
        if not self.allowed():
            return self.send(403, b"Forbidden")
        path = urllib.parse.urlsplit(self.path).path
        # A custom header cannot be sent by another web site without our permission, which we never give.
        if path != "/api/update" or self.headers.get("X-EuroWatcher") != "1":
            return self.send(403, b'{"ok":false,"message":"forbidden"}', "application/json")
        result = update()
        Handler.last_request[0] = time.time()
        return self.send(200 if result["ok"] else 502, json.dumps(result).encode(), "application/json")


def start_server(first_port=FIRST_PORT):
    for port in range(first_port, first_port + 20):
        try:
            server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
        except OSError:
            continue
        server.daemon_threads = True
        threading.Thread(target=server.serve_forever, daemon=True).start()
        return server
    raise OSError("no free local port between %d and %d" % (first_port, first_port + 19))


def running_copy():
    """The address of an EuroWatcher that is already running on this computer, if any."""
    for port in range(FIRST_PORT, FIRST_PORT + 20):
        url = "http://127.0.0.1:%d/" % port
        try:
            with urllib.request.urlopen(url + "api/status", timeout=1) as res:
                if json.loads(res.read().decode()).get("app") == "EuroWatcher":
                    return url
        except (OSError, ValueError):
            continue
    return None


# ---------------------------------------------------------------- the window

def find_app_browser():
    """A Chromium-based browser can show the page as its own app window."""
    if sys.platform == "darwin":
        for app in ("Google Chrome", "Microsoft Edge", "Chromium", "Brave Browser", "Vivaldi"):
            for root in ("/Applications", os.path.expanduser("~/Applications")):
                path = os.path.join(root, app + ".app", "Contents", "MacOS", app)
                if os.path.exists(path):
                    return path
        return None
    for name in ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser", "microsoft-edge", "microsoft-edge-stable", "brave-browser", "vivaldi"):
        path = shutil.which(name)
        if path:
            return path
    return None


def window_still_open():
    # Chromium keeps a "SingletonLock" link in its profile folder while any window of it is open.
    return os.path.lexists(os.path.join(PROFILE, "SingletonLock"))


def open_window(url):
    """Opens the page. Returns the browser process when it got its own window, else None."""
    browser = find_app_browser()
    if browser:
        os.makedirs(PROFILE, exist_ok=True)
        try:
            return subprocess.Popen([browser, "--app=" + url, "--user-data-dir=" + PROFILE, "--no-first-run",
                                     "--no-default-browser-check", "--window-size=1280,900"],
                                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        except OSError as err:
            log("could not start %s: %s" % (browser, err))
    webbrowser.open(url)
    return None


def run(show_window=True):
    other = running_copy()
    if other:
        if show_window:
            open_window(other)
        print("EuroWatcher is already running at " + other)
        return 0
    prepare_data()
    server = start_server()
    url = "http://127.0.0.1:%d/" % server.server_address[1]
    log("EuroWatcher %s serving %s" % (VERSION, url))
    print("EuroWatcher is running at " + url)
    print("Close its window (or press Ctrl+C here) to stop it.")
    proc = open_window(url) if show_window else None
    try:
        if proc is not None:
            proc.wait()
            time.sleep(3)
            while window_still_open():
                time.sleep(2)
        else:
            # Shown in an ordinary browser tab: the page checks in every minute while it is open.
            while time.time() - Handler.last_request[0] < (10 ** 9 if not show_window else 300):
                time.sleep(5)
    except KeyboardInterrupt:
        pass
    server.shutdown()
    return 0


# ---------------------------------------------------------------- self-test

def selftest():
    errors = []
    prepare_data()
    text = read_data().decode("utf-8")
    parsed = parse_file(text)
    again = serialize(parsed["draws"], parsed["checks"])
    a = [l.rstrip(",") for l in text.splitlines() if re.match(r'^\[\d+,"', l)]
    b = [l.rstrip(",") for l in again.splitlines() if re.match(r'^\[\d+,"', l)]
    if a != b:
        first = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
        errors.append("data does not write back the same (row %d)" % (first + 1))
    errors += file_problems(parsed["draws"])[:3]
    server = start_server(FIRST_PORT + 100)
    port = server.server_address[1]

    def ask(method, path, host=None, status=200, contains=None):
        conn = socket.create_connection(("127.0.0.1", port), timeout=10)
        conn.sendall(("%s %s HTTP/1.1\r\nHost: %s\r\nContent-Length: 0\r\nConnection: close\r\n\r\n" % (method, path, host or "127.0.0.1:%d" % port)).encode())
        data = b""
        while True:
            chunk = conn.recv(65536)
            if not chunk:
                break
            data += chunk
        conn.close()
        reply = data.decode("utf-8", "replace")
        first_line = reply.split("\r\n", 1)[0]
        ok = (" %d " % status) in first_line + " " and (contains is None or contains in reply)
        print("  %-5s %-16s %s" % (method, path + (" (other host)" if host else ""), first_line))
        if not ok:
            errors.append("%s %s: expected %d, got %s" % (method, path, status, first_line))

    print("EuroWatcher %s self-test: %d draws on file, latest %s" % (VERSION, len(parsed["draws"]), parsed["draws"][-1]["date"]))
    ask("GET", "/", contains="EuroWatcher")
    ask("GET", "/app.js", contains="EURO_I18N")
    ask("GET", "/i18n.js", contains="Fran")
    ask("GET", "/data/draws.js", contains="window.EURO_DATA")
